// motor.h
// ============================================================
// Публичный интерфейс управления DC-моторами
//
// Модуль предоставляет:
//  - инициализацию драйвера
//  - управление скоростью и направлением
//  - полный стоп (электротормоз)
//
// ВСЯ аппаратная привязка (GPIO, TIM, пины)
// находится в motor.c
// ============================================================
#ifndef MOTOR_H
#define MOTOR_H
#include <stdint.h>

/* ============================================================
 *                    ИДЕНТИФИКАТОР МОТОРА
 * ============================================================ */
typedef enum
{
    MOTOR_A = 0, // левый мотор
    MOTOR_B = 1  // правый мотор
} MotorId;

/* ============================================================
 *                    НАСТРОЙКИ PWM
 * ============================================================ *
 *
 * Диапазон значений speed в Motor_SetSpeed():
 *
 *   speed ∈ [-MOTOR_PWM_MAX .. +MOTOR_PWM_MAX]
 *
 * Знак определяет направление,
 * модуль — мощность.
 *
 * Реальная частота PWM и таймер
 * скрыты внутри motor.c
 *
 * ============================================================ */
#define MOTOR_PWM_MAX 1000
/* ============================================================
 *                    ПУБЛИЧНЫЙ API
 * ============================================================ */

// Инициализация драйвера моторов (вызывать 1 раз)
void Motor_Init(void);

// Управление мотором:
//  speed > 0 → вперёд
//  speed < 0 → назад
//  speed = 0 → стоп
void Motor_SetSpeed(MotorId id, int16_t speed);

// Полный стоп мотора (эквивалент speed = 0)
void Motor_Stop(MotorId id);

#endif // MOTOR_H
